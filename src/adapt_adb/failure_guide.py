def _build(guides: tuple[FailureGuide, ...]) -> dict[str, FailureGuide]:
    built: dict[str, FailureGuide] = {}
    for guide in guides:
        if guide.id in built:
            raise ValueError(f"Duplicate failure guide id: {guide.id}")
        built[guide.id] = guide
    return built


GUIDES: Mapping[str, FailureGuide] = _build(_GUIDE_LIST + _PHASE4_GUIDES + tuple(RECEIVER_GUIDES.values()) + _NATIVE_RECEIVER_GUIDES)
RENAMED: Mapping[str, str] = {}


def doctor_remediation_text(failure_id: str | None, variant: str | None = None, **values: str) -> str | None:
    """Doctor's remediation text for a check branch: the single source for `checks[].remediation`.

    ``variant`` picks an alternative text recorded in ``doctor_variants`` (another check that
    shares the guide, or a host variant such as "debian"); otherwise ``doctor_remediation`` is
    used. Each ``<NAME>`` placeholder is replaced by the value passed as ``NAME=...``.
    """
    guide = GUIDES.get(RENAMED.get(failure_id, failure_id)) if failure_id else None
    if guide is None:
        return None
    text = dict(guide.doctor_variants).get(variant, guide.doctor_remediation) if variant else guide.doctor_remediation
    if text is None:
        return None
    for name, value in values.items():
        text = text.replace(f"<{name}>", value)
    return text
