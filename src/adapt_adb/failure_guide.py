"""Failure guidance registry: what happened, possible causes and what to try next.

Data only. This module imports nothing from ``adapt_adb`` so doctor, help and MCP
code can import it without cycles. Guide IDs are a public API (they appear in
JSON and MCP output): never rename one; move a retired ID into ``RENAMED``.

Text rules (enforced by ``tests/test_failure_guide.py``):
- ``summary`` describes what ADAPT observed; causes are possibilities only.
- Text may interpolate only ``TEMPLATE_FIELDS``; commands use CAPS placeholders.
- Prohibitions live in ``avoid``; steps never recommend them.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, Mapping

Effect = Literal["read_only", "changes_host", "changes_device", "on_phone", "manual"]
# All pairs must match: context key -> allowed values. Unknown (None) keeps the item.
Condition = tuple[tuple[str, tuple[object, ...]], ...]

NAMESPACES: frozenset[str] = frozenset({
    "adb", "device", "wireless", "setup", "input", "prefs", "mcp", "devopts", "dex",
    "dexpc", "android", "detect", "desktop", "app", "logs", "debug", "ssh", "tailscale",
    "tools", "scrcpy", "everything", "host", "internal",
})
TEMPLATE_FIELDS = frozenset({"device_state", "ready_count", "not_ready_count", "api_level"})

ON_WINDOWS: Condition = (("host_os", ("windows",)),)
ON_LINUX: Condition = (("host_os", ("linux",)),)
ON_MACOS: Condition = (("host_os", ("macos",)),)
NOT_WINDOWS: Condition = (("host_os", ("linux", "macos", "other")),)


@dataclass(frozen=True)
class Cause:
    text: str                          # a possibility, never asserted
    when: Condition = ()               # dropped when context contradicts; kept when unknown
    first_when: Condition = ()         # promoted to the top when context matches
    if_unknown: str | None = None      # label when a `when` key is unknown: "On Linux"


@dataclass(frozen=True)
class Step:
    text: str                          # imperative, plain language
    command: str | None = None         # exact, copy-pasteable; placeholders in CAPS
    effect: Effect = "read_only"
    needs_admin: bool = False
    when: Condition = ()
    if_unknown: str | None = None      # label when a `when` key is unknown: "If this PC runs Linux"
    mcp_tool: str | None = None        # equivalent MCP tool for AI clients
    first_when: Condition = ()


@dataclass(frozen=True)
class McpHint:
    next_tool: str | None                       # first tool to call; filtered by AccessPolicy
    fallback_tools: tuple[str, ...] = ()        # used when next_tool is not exposed
    retry: Literal["safe_now", "with_changed_arguments", "after_user_action", "not_useful"] = "not_useful"
    user_action_required: bool = False          # the human must act (tap Allow, replug)
    argument_hint: str | None = None
    ask_user: str | None = None                 # one static sentence an agent may relay


@dataclass(frozen=True)
class FailureGuide:
    id: str
    summary: str
    certainty: Literal["observed", "inferred"]
    causes: tuple[Cause, ...]
    steps: tuple[Step, ...]
    help_topic: str | None
    docs: str | None = None                     # repo-relative path; never a URL
    variability: str | None = None
    avoid: tuple[str, ...] = ()
    diagnose: str | None = "adapt doctor"
    aliases: tuple[str, ...] = ()
    commands: tuple[str, ...] = ()
    doctor_check: str | None = None
    # The single source of doctor's `remediation` text for the check branch this guide explains.
    # `<NAME>` marks a value doctor fills at run time (see doctor_remediation_text).
    doctor_remediation: str | None = None
    doctor_variants: tuple[tuple[str, str], ...] = ()   # (variant, text): another check or host variant
    mcp: McpHint | None = None


